package tiameds.pharmabackend.dto.auditReports;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;
import lombok.Data;

import java.time.LocalDateTime;

@Data
@JsonPropertyOrder({
        "summary", "adjustmentTransactions", "adjustmentTypeSummary", "adjustmentReasonSummary",
        "generatedBy", "generatedOn"})
public class StockAdjustmentReportResponse {

    private StockAdjustmentReportSummaryDto summary;

    private StockAdjustmentReportPageDto adjustmentTransactions;

    // Adjustment Type Summary: quantity per type; the last row is Net Adjustment.
    private StockAdjustmentReportTypeSummaryDto adjustmentTypeSummary;

    // Adjustment Reason Summary: in / out / net per reason, plus the Total row.
    private StockAdjustmentReportReasonSummaryDto adjustmentReasonSummary;

    // Report header: "Generated by", "Generated on: 08-Oct-2026 05:30 PM".
    private String generatedBy;

    @JsonFormat(pattern = "dd-MMM-yyyy hh:mm a", locale = "en")
    private LocalDateTime generatedOn;
}
