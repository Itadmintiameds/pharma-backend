package tiameds.pharmabackend.dto.auditReports;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;
import lombok.Data;

import java.time.LocalDate;
import java.time.LocalDateTime;

@Data
@JsonPropertyOrder({
        "summary", "movementDetails", "fromDate", "toDate", "generatedBy", "generatedOn"})
public class StockMovementReportResponse {

    // Report header: "Period: 01-Oct-2026 to 08-Oct-2026".
    @JsonFormat(pattern = "dd-MMM-yyyy", locale = "en")
    private LocalDate fromDate;

    @JsonFormat(pattern = "dd-MMM-yyyy", locale = "en")
    private LocalDate toDate;

    private StockMovementReportSummaryDto summary;

    private StockMovementReportPageDto movementDetails;

    // Report header: "Generated by", "Generated on: 08-Oct-2026 05:30 PM".
    private String generatedBy;

    @JsonFormat(pattern = "dd-MMM-yyyy hh:mm a", locale = "en")
    private LocalDateTime generatedOn;
}
