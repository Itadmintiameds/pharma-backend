package tiameds.pharmabackend.dto.auditReports;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;
import lombok.Data;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;

@Data
@JsonPropertyOrder({
        "reportName", "fromDate", "toDate", "groupBy", "pharmacies",
        "summary", "salesBook", "generatedBy", "generatedOn"})
public class GrossProfitSalesBookResponse {

    // "G.P. ON CONSOLIDATED SALES BOOK"
    private String reportName;

    // Date Range: 01-09-2026 to 30-09-2026
    @JsonFormat(pattern = "dd-MM-yyyy")
    private LocalDate fromDate;

    @JsonFormat(pattern = "dd-MM-yyyy")
    private LocalDate toDate;

    // DAY or MONTH
    private String groupBy;

    // Header block (name, address, phone, email, GSTIN) of each pharmacy
    // the report covers.
    private List<GrossProfitSalesBookPharmacyDto> pharmacies;

    private GrossProfitSalesBookSummaryDto summary;

    private GrossProfitSalesBookPageDto salesBook;

    // "Generated by: Admin User", "Generated on: 01-Oct-2026 09:30 AM".
    private String generatedBy;

    @JsonFormat(pattern = "dd-MMM-yyyy hh:mm a", locale = "en")
    private LocalDateTime generatedOn;
}
