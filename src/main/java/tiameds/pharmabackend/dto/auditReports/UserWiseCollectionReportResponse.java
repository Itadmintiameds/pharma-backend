package tiameds.pharmabackend.dto.auditReports;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;
import lombok.Data;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;

@Data
@JsonPropertyOrder({
        "summary", "userWiseSummary", "collectionTransactions",
        "fromDate", "toDate",
        "generatedBy", "generatedOn"})
public class UserWiseCollectionReportResponse {

    private UserWiseCollectionReportSummaryDto summary;

    // User-wise Collection Summary: every matching user, not paged. Its Total
    // row is summary.
    private List<UserWiseCollectionUserRowDto> userWiseSummary;

    private UserWiseCollectionReportPageDto collectionTransactions;

    // "Reporting Date: 12-Oct-2026" (or a from - to range).
    @JsonFormat(pattern = "dd-MMM-yyyy", locale = "en")
    private LocalDate fromDate;

    @JsonFormat(pattern = "dd-MMM-yyyy", locale = "en")
    private LocalDate toDate;

    // "Generated by", "Generated on: 12-Oct-2026 05:30 PM".
    private String generatedBy;

    @JsonFormat(pattern = "dd-MMM-yyyy hh:mm a", locale = "en")
    private LocalDateTime generatedOn;
}
