    @Override
    public ReportExport prepare(String report, String format, FinancialReportFilter filter, UserDetails user) {

        // Three sections rather than one paged table, so it writes its own file.
        if (report != null && GST_SALES_PURCHASE_SUMMARY.equals(report.trim())) {
            return gstReportService.exportSalesPurchaseSummary(format, filter, user);
        }

        ReportExportDefinition<?> definition = definitions.get(report == null ? null : report.trim());

        if (definition == null) {
            throw new IllegalArgumentException(
                    "Unknown report: " + report + ". Use one of " + String.join(", ", definitions.keySet())
                            + ", " + GST_SALES_PURCHASE_SUMMARY + ".");
        }

        return prepare(report.trim(), definition, ExportFormat.parse(format), filter, user);
    }


    // Runs the first batch now, so bad filters, missing access and size
    // limits fail before any of the file has been sent.
    private <T> ReportExport prepare(
            String report,
            ReportExportDefinition<T> definition,
            ExportFormat format,
            FinancialReportFilter filter,
            UserDetails user) {

        filter.useExportBatches(BATCH_SIZE);
        filter.setPage(0);

        FinancialReportResponse<?, T> first = definition.fetch().apply(filter, user);
        long totalRows = first.getBillDetails().getTotalElements();

        if (format == ExportFormat.XLSX && totalRows > EXCEL_ROW_LIMIT) {
            throw new IllegalArgumentException(
                    "Too many rows for Excel (" + totalRows + "). Narrow the filters or download CSV.");
        }

        String pharmacies = pharmacyNames(support.resolvePharmacyIds(filter, user));
        String period = period(definition, filter);
        String fileName = report + "_" + fileDate(definition, filter) + format.extension();

        return new ReportExport() {

            @Override
            public String fileName() {
                return fileName;
            }

            @Override
            public String contentType() {
                return format.contentType();
            }

            @Override
            public void writeTo(OutputStream out) throws IOException {

                try (ReportTableWriter writer = format.open(out)) {

                    writer.title(definition.title());
                    writer.line("Pharmacy", pharmacies);
                    writer.line(definition.businessDay() ? "Date" : "Period", period);
                    writer.line("Generated By", first.getGeneratedBy());
                    writer.line("Generated On", first.getGeneratedOn());
                    writer.blank();

                    for (Map.Entry<String, Object> kpi : kpiLines(first.getKpi()).entrySet()) {
                        writer.line(kpi.getKey(), kpi.getValue());
                    }

                    writer.blank();
                    writer.header(definition.columns().stream().map(ExportColumn::header).toList());

                    FinancialReportResponse<?, T> batch = first;
                    int page = 0;

                    while (true) {

                        for (T row : batch.getBillDetails().getContent()) {
                            List<Object> values = new ArrayList<>(definition.columns().size());
                            for (ExportColumn<T> column : definition.columns()) {
                                values.add(column.value().apply(row));
                            }
                            writer.row(values);
                        }

                        page++;

                        if (page >= batch.getBillDetails().getTotalPages()
                                || batch.getBillDetails().getContent().isEmpty()) {
                            break;
                        }

                        filter.setPage(page);
                        batch = definition.fetch().apply(filter, user);
                    }

                    writer.finish();
                }
            }
        };
    }


    private <T> void register(
            String report,
            String title,
            boolean businessDay,
            BiFunction<FinancialReportFilter, UserDetails, FinancialReportResponse<?, T>> fetch,
            List<ExportColumn<T>> columns) {

        definitions.put(report, new ReportExportDefinition<>(title, businessDay, fetch, columns));
    }


    private static <T> ExportColumn<T> col(String header, java.util.function.Function<T, ?> value) {
        return ExportColumn.of(header, value);
    }


    private String pharmacyNames(List<String> pharmacyIds) {

        Map<String, String> names = new HashMap<>();

        for (PharmacyDetails pharmacy : pharmacyDetailsRepository.findAllById(pharmacyIds)) {
            names.put(pharmacy.getPharmacyId(), pharmacy.getPharmacyName());
        }

        return String.join(", ", pharmacyIds.stream()
                .map(id -> FinancialReportSupport.hasText(names.get(id)) ? names.get(id) : id)
                .toList());
    }


    // The period as the report applies it: day closing reports cover one date
    // (today when none is sent); the others the date, the range, or all dates.
    private static String period(ReportExportDefinition<?> definition, FinancialReportFilter filter) {

        if (definition.businessDay()) {
            return (filter.getDate() == null ? LocalDate.now() : filter.getDate()).format(DISPLAY_DATE);
        }

        if (filter.getDate() != null) {
            return filter.getDate().format(DISPLAY_DATE);
        }

        if (filter.getFromDate() != null && filter.getToDate() != null) {
            return filter.getFromDate().format(DISPLAY_DATE) + " to " + filter.getToDate().format(DISPLAY_DATE);
        }

        if (filter.getFromDate() != null) {
            return "From " + filter.getFromDate().format(DISPLAY_DATE);
        }

        if (filter.getToDate() != null) {
            return "Up to " + filter.getToDate().format(DISPLAY_DATE);
        }

        return "All dates";
    }


    private static String fileDate(ReportExportDefinition<?> definition, FinancialReportFilter filter) {

        if (filter.getDate() != null) {
            return filter.getDate().toString();
        }

        if (!definition.businessDay() && filter.getFromDate() != null && filter.getToDate() != null) {
            return filter.getFromDate() + "_to_" + filter.getToDate();
        }

        return LocalDate.now().toString();
    }


    // KPI fields as label / value lines, e.g. totalSalesAmount -> "Total Sales
    // Amount". Nested KPI objects (per patient type) are flattened with their
    // name as a prefix: ip.billCount -> "IP Bill Count".
    private static Map<String, Object> kpiLines(Object kpi) {

        Map<String, Object> lines = new LinkedHashMap<>();
        addKpiLines(lines, "", kpi);

        return lines;
    }


    private static void addKpiLines(Map<String, Object> lines, String prefix, Object kpi) {

        if (kpi == null) {
            return;
        }

        try {
            Map<String, PropertyDescriptor> properties = new HashMap<>();

            for (PropertyDescriptor property : Introspector.getBeanInfo(kpi.getClass(), Object.class)
                    .getPropertyDescriptors()) {
                properties.put(property.getName(), property);
            }

            // Field declaration order, so the lines follow the KPI cards.
            for (Field field : kpi.getClass().getDeclaredFields()) {

                PropertyDescriptor property = properties.get(field.getName());

                if (Modifier.isStatic(field.getModifiers()) || property == null || property.getReadMethod() == null) {
                    continue;
                }

                Object value = property.getReadMethod().invoke(kpi);
                String label = prefix + humanize(property.getName());

                if (value == null || isSimple(value)) {
                    lines.put(label, value);
                } else {
                    addKpiLines(lines, label + " ", value);
                }
            }
        } catch (IntrospectionException | IllegalAccessException | InvocationTargetException e) {
            throw new IllegalStateException("Could not read report KPIs", e);
        }
    }


    private static boolean isSimple(Object value) {
        return value instanceof Number || value instanceof String || value instanceof Boolean
                || value instanceof LocalDate || value instanceof LocalDateTime || value instanceof BigDecimal;
    }


    // camelCase -> Title Case; short all-lowercase names are acronyms (ip, op, upi).
    private static String humanize(String name) {

        if (name.length() <= 3 && name.equals(name.toLowerCase())) {
            return name.toUpperCase();
        }

        String spaced = name.replaceAll("([a-z0-9])([A-Z])", "$1 $2");

        return Character.toUpperCase(spaced.charAt(0)) + spaced.substring(1);
    }
